let currentLang = "en";

export function getLanguage() {
  try {
    if (typeof localStorage !== "undefined") {
      const saved = localStorage.getItem("localwork_lang");
      if (saved === "ta" || saved === "en") return saved;
    }
  } catch (e) {}
  return "en";
}

export function t(key, params = {}) {
  const langTable = translations[currentLang] || translations.en;
  let text = langTable[key] || translations.en[key] || key;
  for (const [pKey, pVal] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${pKey}\\}`, "g"), pVal);
  }
  return text;
}

export function setLanguage(lang, callback) {
  currentLang = lang === "ta" ? "ta" : "en";
  try {
    if (typeof localStorage !== "undefined") {
      localStorage.setItem("localwork_lang", currentLang);
    }
  } catch (e) {}

  if (typeof document !== "undefined") {
    document.documentElement.setAttribute("lang", currentLang);

    // Update topbar button
    const topbarBtn = document.getElementById("lang-toggle-btn");
    if (topbarBtn) {
      const label = topbarBtn.querySelector(".lang-toggle-label");
      if (label) label.textContent = currentLang === "ta" ? "English" : "தமிழ்";
      topbarBtn.title = currentLang === "ta" ? "Switch to English" : "Switch to Tamil (தமிழ்)";
    }

    // Update sidebar button
    const sidebarBtn = document.getElementById("sidebar-lang-toggle");
    if (sidebarBtn) {
      const sLabel = sidebarBtn.querySelector(".lang-sidebar-label");
      if (sLabel) sLabel.textContent = currentLang === "ta" ? "English (ஆங்கிலம்)" : "தமிழ் (Tamil)";
      sidebarBtn.title = currentLang === "ta" ? "Switch to English" : "Switch to Tamil (தமிழ்)";
    }

    // Update AI header button if present
    const aiLangBtn = document.getElementById("ai-lang-btn");
    if (aiLangBtn) {
      aiLangBtn.textContent = currentLang === "ta" ? "🌐 English" : "🌐 தமிழ்";
      aiLangBtn.title = currentLang === "ta" ? "Switch to English" : "Switch to Tamil (தமிழ்)";
    }

    // Update AI fab label
    const aiFabLabel = document.querySelector(".ai-fab-label");
    if (aiFabLabel) {
      aiFabLabel.textContent = t("ai_fab_label");
    }

    // Apply to all elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = t(key);
      if (val) el.textContent = val;
    });

    // Apply to all elements with data-i18n-html
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      const val = t(key);
      if (val) el.innerHTML = val;
    });

    // Apply to all inputs with data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const val = t(key);
      if (val) el.placeholder = val;
    });
  }

  if (typeof callback === "function") {
    callback(currentLang);
  }
}

export function initLanguage(callback) {
  const initial = getLanguage();
  setLanguage(initial, callback);
}
