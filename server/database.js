const { Pool } = require("pg");
const bcrypt = require("bcryptjs");
const env = require("../config/env");

if (!env.databaseUrl) {
  throw new Error("DATABASE_URL is missing. Add it to your .env file.");
}

const pool = new Pool({
  connectionString: env.databaseUrl,
  ssl: { rejectUnauthorized: false }
});

const db = {
  prepare(sql) {
    return {
      get: async (...params) => {
        const result = await pool.query(sql, params);
        return result.rows[0];
      },
      all: async (...params) => {
        const result = await pool.query(sql, params);
        return result.rows;
      },
      run: async (...params) => {
        const result = await pool.query(sql, params);
        return {
          changes: result.rowCount,
          lastInsertRowid: result.rows[0]?.id
        };
      }
    };
  },
  close: () => pool.end()
};

const publicUser = row => row && ({
  id: row.id,
  name: row.name,
  email: row.email,
  phone: row.phone,
  location: row.location,
  role: row.role,
  service: row.profile_service ?? row.service ?? null,
  experience: row.profile_experience ?? row.experience ?? null,
  description: row.profile_description ?? row.description ?? null,
  availability: row.profile_availability ?? row.availability ?? null,
  createdAt: row.created_at
});

async function initializeDatabase() {

  // User accounts
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL,
      phone TEXT NOT NULL,
      location TEXT NOT NULL,
      role TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);

  await pool.query(`
    ALTER TABLE users
    DROP CONSTRAINT IF EXISTS users_role_check
  `);

  await pool.query(`
    UPDATE users SET role='customer' WHERE role='workman'
  `);

  await pool.query(`
    ALTER TABLE users
    ADD CONSTRAINT users_role_check
    CHECK(role IN ('customer','admin'))
  `);

  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx
    ON users (LOWER(email))
  `);

  // Workman profiles
  await pool.query(`
    CREATE TABLE IF NOT EXISTS workman_profiles (
      user_id INTEGER PRIMARY KEY
        REFERENCES users(id) ON DELETE CASCADE,
      service TEXT NOT NULL,
      experience INTEGER,
      description TEXT,
      availability TEXT NOT NULL DEFAULT 'Available'
        CHECK(availability IN ('Available','Busy')),
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_workman_profiles_service
    ON workman_profiles(service)
  `);

  // Bookings
  await pool.query(`
    CREATE TABLE IF NOT EXISTS bookings (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      workman_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      customer_name TEXT NOT NULL,
      phone TEXT NOT NULL,
      address TEXT NOT NULL,
      booking_date TEXT NOT NULL,
      booking_time TEXT NOT NULL,
      notes TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'Pending'
        CHECK(status IN ('Pending','Accepted','Declined','Completed','Cancelled')),
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_bookings_customer
    ON bookings(customer_id)
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_bookings_workman
    ON bookings(workman_id)
  `);

  console.log("PostgreSQL database initialized successfully.");
}

async function bootstrapAdmin() {
  if (!env.adminEmail || !env.adminPassword) {
    console.warn("Admin bootstrap skipped: set ADMIN_EMAIL and ADMIN_PASSWORD in .env.");
    return;
  }

  if (env.adminPassword.length < 12) {
    throw new Error("ADMIN_PASSWORD must be at least 12 characters.");
  }

  const existing = await pool.query(
    "SELECT id FROM users WHERE LOWER(email) = LOWER($1)",
    [env.adminEmail]
  );

  const hash = await bcrypt.hash(env.adminPassword, 12);

  if (existing.rows.length) {
    await pool.query(
      "UPDATE users SET role='admin', password_hash=$1 WHERE id=$2",
      [hash, existing.rows[0].id]
    );
  } else {
    await pool.query(
      `INSERT INTO users (name,email,phone,location,role,password_hash)
       VALUES ($1,$2,$3,$4,'admin',$5)`,
      ["LocalWork Administrator", env.adminEmail, "Not public", "Admin", hash]
    );
  }

  console.log(`Admin account ready for ${env.adminEmail}`);
}

module.exports = {
  db,
  pool,
  publicUser,
  initializeDatabase,
  bootstrapAdmin
};